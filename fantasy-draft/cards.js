/* Fantasy points a card earns its drafter on top of OVR, by the drafter's own choice on it.
   Partner is the alliance card: it pays little to the country that drafts it, and FENCE_PARTNER_ALLY
   to every OTHER team that rates it Partner when somebody else holds it (results screen). */
const FENCE_FIT = { secure: 18, preserve: 12, catch_up: 9, accelerate: 9, partner: 3, watch: -6 };
const FENCE_PARTNER_ALLY = 4;
/* portfolio bonuses (results screen) */
const STAGE_COVERAGE_PTS = 5;     // per distinct stage held
const CHAIN_LINK_PTS = 6;         // per adjacent pair of stages held in one technology
const FULL_CHAIN_PTS = 10;        // extra for Extraction through Assembly in one technology

function ratingOf(allyId, n) {
  const r = ((FD_OSI.ratings || {})[allyId] || {})[n];
  if (!r) return null;
  return { fence: r[0], choice: r[1], need: r[2], prize: r[3], cp: r[4] };
}

/* Fast lookup helpers (SUB_BY_N also resolves the legacy sub-sectors of old leagues) */
const ALLY_BY_ID = Object.fromEntries(ALLIES.map(a => [a.id, a]));
const SUB_BY_N = Object.fromEntries([...LEGACY_SUBSECTORS, ...CARDS].map(s => [s.n, s]));
const isCard = (sub) => !!(sub && sub.tech);

/* colours + labels of a card (by technology) or a legacy sub-sector (by category) */
function catMeta(sub) {
  if (isCard(sub)) {
    const t = TECHS[sub.tech] || { short: sub.tech.toUpperCase(), c1: "#64748b", c2: "#94a3b8" };
    const st = STAGES[sub.cat];
    return { c1: t.c1, c2: t.c2, short: st.short, key: st.id, label: `${st.name} · ${sub.tech}` };
  }
  const c = CATEGORIES[sub.cat];
  return { c1: c.c1, c2: c.c2, short: c.short, key: c.id, label: `${c.id} · ${c.short}` };
}

/* the fit a country gets from a card: its choice's points (legacy: home synergy + signature) */
function fitOf(ally, sub) {
  if (!isCard(sub)) return (ally.home[sub.cat] || 0) + (ally.picks.includes(sub.n) ? 6 : 0);
  const r = ratingOf(ally.id, sub.n);
  return r && r.choice in FENCE_FIT ? FENCE_FIT[r.choice] : 0;
}

/* Fantasy score of a card for a given ally (OVR + fence fit) */
function scoreFor(ally, sub) {
  return sub.ovr + fitOf(ally, sub);
}

/* Portfolio bonuses for a finished roster: stage coverage, technology chains, Partner payouts.
   others: the card ids every OTHER team holds. */
function portfolioBonus(allyId, roster, others) {
  const cards = roster.map(n => SUB_BY_N[n]).filter(isCard);
  const stages = new Set(cards.map(c => c.cat));
  const coverage = stages.size * STAGE_COVERAGE_PTS;
  let combo = 0; const chains = [];
  const byTech = {};
  cards.forEach(c => (byTech[c.tech] = byTech[c.tech] || new Set()).add(STAGE_ORDER.indexOf(c.cat)));
  Object.entries(byTech).forEach(([tech, set]) => {
    let links = 0;
    for (let i = 0; i < STAGE_ORDER.length - 1; i++) if (set.has(i) && set.has(i + 1)) links++;
    const full = [0, 1, 2, 3].every(i => set.has(i));
    const pts = links * CHAIN_LINK_PTS + (full ? FULL_CHAIN_PTS : 0);
    if (pts) { combo += pts; chains.push({ tech, links, full, pts }); }
  });
  const partnerCards = (others || []).filter(n => { const r = ratingOf(allyId, n); return r && r.choice === "partner"; });
  const partner = partnerCards.length * FENCE_PARTNER_ALLY;
  return { coverage, stages: stages.size, combo, chains, partner, partnerCards };
}
