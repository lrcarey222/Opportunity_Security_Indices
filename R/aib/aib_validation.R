# Allied Industrial Base (AIB): the validation chains (docs/aib_methodology.md, 15). For a few nodes
# whose policy logic is easy to inspect the module writes the whole chain
#   shock exposure -> existing resilience -> optimized trade relationships -> coordination
#   dividend -> residual capacity gap -> investment partners -> proposed compact membership ->
#   node-level policy implications
# as a table and as text. The chains report what the model produced; nothing is tuned to them.

aib_validation_chains <- function(cases, classified, node_table, partners, investment, compacts, members,
                                  headline_shock, headline_scenario, nodes, headline_increment = 0.10) {
  pct <- function(x) ifelse(is.na(x), "n/a", sprintf("%.1f%%", 100 * x))
  usd <- function(x) ifelse(is.na(x), "n/a", sprintf("$%.0fm", x / 1e6))
  rows <- list()
  md <- c(sprintf("# AIB validation chains (%s, %s scenario)", headline_shock, headline_scenario), "",
          "Generated by scripts/32_build_aib_partnerships.R. Each chain reports the model's own numbers; the",
          "methodology was not adjusted to produce these answers.", "")
  for (case in cases) {
    ids <- nodes$node_id[nodes$sub_sector == case]
    if (!length(ids)) ids <- nodes$node_id[grepl(case, nodes$sub_sector, fixed = TRUE)]
    if (!length(ids)) {
      md <- c(md, paste0("## ", case), "", "Not found among the nodes.", "")
      next
    }
    for (nid in ids) {
      cl <- classified[classified$node_id == nid, , drop = FALSE]
      if (!nrow(cl)) next
      nt <- node_table[node_table$node_id == nid, , drop = FALSE][1, ]
      pr <- partners[partners$node_id == nid & partners$shock_id == headline_shock & partners$scenario == headline_scenario &
                       partners$relationship != "domestic retention", , drop = FALSE]
      pr <- pr[order(-pr$delta_usd), , drop = FALSE]
      top_tr <- if (nrow(pr)) paste(utils::head(sprintf("%s->%s %s (%s, Export Opportunity %s)", pr$exporter_iso, pr$importer_iso,
                                                        usd(pr$delta_usd), pr$relationship,
                                                        ifelse(is.na(pr$export_opportunity), "n/a", sprintf("%.2f", pr$export_opportunity))), 5),
                                    collapse = "; ") else "none"
      iv <- if (!is.null(investment) && nrow(investment)) investment[investment$node_id == nid & investment$shock_id == headline_shock & investment$scenario == headline_scenario, , drop = FALSE] else NULL
      top_iv <- "not simulated (residual gap below the threshold)"
      if (!is.null(iv) && nrow(iv)) {
        hi <- iv[abs(iv$increment - headline_increment) < 1e-9, , drop = FALSE]
        if (!nrow(hi)) hi <- iv
        hi <- hi[order(hi$host_rank), , drop = FALSE]
        top_iv <- paste(utils::head(sprintf("%s (gain %s, HHI change %+.3f, %s, Friendshore %s)", hi$host_iso, pct(hi$marginal_resilience_gain),
                                            hi$delta_hhi, hi$capability_basis,
                                            ifelse(is.na(hi$friendshore_need_weighted), "n/a", sprintf("%.2f", hi$friendshore_need_weighted))), 3),
                        collapse = "; ")
      }
      cid <- nt$compact_id
      comp_txt <- "no compact: the node does not need one under this shock"
      if (!is.na(cid) && nzchar(cid)) {
        cp <- compacts[compacts$compact_id == cid, , drop = FALSE]
        mm <- members[members$compact_id == cid & members$in_minimum_coalition, , drop = FALSE]
        role_txt <- if (nrow(mm)) paste(sprintf("%s: %s", names(split(mm$iso3, mm$role)), vapply(split(mm$iso3, mm$role), function(x) paste(sort(unique(x)), collapse = " "), "")), collapse = "; ") else ""
        comp_txt <- sprintf("%s %s (%s, %s); minimum coalition: %s; roles: %s", cid, cp$compact_name, cp$compact_archetype, cp$compact_type,
                            cp$minimum_coalition, role_txt)
      }
      chain <- tibble::tibble(
        case = case, node_id = nid,
        step = c("0 data quality", "1 shock exposure", "2 existing resilience", "3 optimized trade relationships", "4 coordination dividend",
                 "5 residual capacity gap", "6 investment partners", "7 proposed compact membership", "8 node-level policy implication"),
        value = c(
          sprintf("%s%s", cl$data_quality, if (!is.null(cl$flags) && !is.na(cl$flags) && nzchar(cl$flags)) paste0(": ", cl$flags) else ""),
          sprintf("%s of universe demand (%s) lost; baseline largest supplier %s", pct(cl$shock_exposure), usd(cl$demand_usd), cl$baseline_largest_supplier),
          sprintf("static coverage %s; existing relationships restore to %s", pct(cl$static_coverage), pct(cl$existing_coverage)),
          sprintf("optimized coverage %s; leading new/expanded relationships: %s", pct(cl$optimized_coverage), top_tr),
          pct(cl$coordination_dividend),
          sprintf("%s of demand (%s)", pct(cl$residual_gap), usd(cl$residual_gap * cl$demand_usd)),
          top_iv,
          comp_txt,
          sprintf("%s: %s -> %s", cl$node_classification, cl$classification_reason, aib_class_treatment(cl$node_classification))
        )
      )
      rows[[length(rows) + 1]] <- chain
      md <- c(md, sprintf("## %s (`%s`, %s)", case, nid, cl$data_quality), "")
      md <- c(md, paste0("- **", sub("^[0-9] ", "", chain$step), ":** ", chain$value), "")
    }
  }
  list(table = dplyr::bind_rows(rows), markdown = md)
}
